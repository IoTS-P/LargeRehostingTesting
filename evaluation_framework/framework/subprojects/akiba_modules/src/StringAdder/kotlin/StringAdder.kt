package org.iotsplab.akiba.process

import ghidra.features.base.memsearch.searcher.MemoryMatch
import ghidra.program.flatapi.FlatProgramAPI
import ghidra.program.model.address.Address
import ghidra.program.model.data.StringDataType
import ghidra.program.model.listing.Program
import ghidra.program.model.util.CodeUnitInsertionException
import org.apache.logging.log4j.Level
import org.iotsplab.akiba.module.AkibaModule
import org.iotsplab.akiba.utils.WithTableColumn
import org.iotsplab.akiba.utils.assembly.isValidToEndBasicBlock
import org.iotsplab.akiba.utils.function.OrphanCodeKiller
import org.iotsplab.akiba.utils.memory.MemoryUtil
import org.iotsplab.akiba.utils.memory.RegexPattern
import org.iotsplab.akiba.utils.reference.isValidCodeTarget
import org.iotsplab.akiba.utils.string.AsciiSequenceSearcher
import org.iotsplab.akiba.utils.string.RegexSearcher
import org.iotsplab.akiba.utils.string.RegexSearcher.Companion.UNIX_COLOR_ASCII_REGEX
import org.iotsplab.akiba.utils.string.allStrings
import org.iotsplab.akiba.utils.string.StringSearchResult

/**
 * StringAdder: Add missing strings of the program
 *
 * Detailed process:
 *  - Clear codes that don't belong to any function, to avoid data being wrongly recognized as codes
 *  - Search all the program with multiple searchers and define those strings, the length threshold set in default to 5
 *  - Fill the small gaps generated by super short strings between strings to increase recognition rates
 *
 * @author: Hornos3, Hornos3@github.com
 */
@WithTableColumn("added_count", "INTEGER")
class StringAdder(
    id: Int,
    program: Program,
    consoleLogLevel: Level = Level.INFO,
    fileLogLevel: Level = Level.INFO,
    tableName: String? = null
) : AkibaModule (
    id = id,
    program = program,
    consoleLogLevel = consoleLogLevel,
    fileLogLevel = fileLogLevel,
    tableName = tableName
) {
    val prog: Program
        get() = program!!
    private val api: FlatProgramAPI = FlatProgramAPI(program)
    private var searchResult: MutableList<StringSearchResult> = mutableListOf()
    private val searchers: MutableList<RegexSearcher> = defaultSearcher(program)
    private var totalCount = 0

    @Throws(Exception::class)
    override suspend fun startProcess() {
        // Those data who are wrongly recognized as functions usually has no function definition, making these fake
        // codes orphans, undefined them and then we can get more strings
        OrphanCodeKiller.process(prog)

        for (searcher in searchers)
            searchResult.addAll(searcher.search())
        searchResult = StringSearchResult.removeOverlapMatches(searchResult).toMutableList()

        printResults()
        totalCount += searchResult.size

        defineResults()
        fillSmallStringGaps()

        updateData(mapOf("added_count" to totalCount))
    }

    private fun printResults() {
        logger.debug("Will add ${searchResult.size} results")
        for (result in searchResult) {
            logger.debug(result.toString())
        }
    }

    @Throws(CodeUnitInsertionException::class)
    fun defineResults() {
        val dt = StringDataType()
        for (result in searchResult) {
            // We need to check if there is any code reference pointing towards there
            var needToSkip: Boolean = false
            api.getInstructionContaining(result.address) ?. let { instruction ->
                // Check if this instruction has any code xref pointing at it

                // If no reference, we still need to check the previous code, it must be a valid ending instruction of
                // an assembly basic block
                if (prog.referenceManager.getReferencesTo(result.address).toCollection(mutableListOf())
                    .any { it.isValidCodeTarget() } || !instruction.previous.isValidToEndBasicBlock()) {
                    logger.debug("Skipped {}", result)
                    needToSkip = true
                }
            }
            if (needToSkip)
                continue

            prog.listing.createData(result.address, dt, result.size)
            logger.debug("Created data for {}", result)
            totalCount++
        }
    }

    /**
     * Sometimes there could be small strings in gaps of longer strings, trying to fill it
     */
    private fun fillSmallStringGaps(maxGapSize: Int = FILL_GAP_MAX_SIZE) {
        val allStrings: List<StringSearchResult> = prog.allStrings()
        val dt = StringDataType()
        allStrings.forEachIndexed { index, _ -> run {
            if (index == allStrings.lastIndex) { return@run }
            val gapStart = allStrings[index].address.add(allStrings[index].size.toLong())
            val gapEnd = allStrings[index + 1].address
            // skip too large gaps
            if (gapEnd.subtract(gapStart) > maxGapSize || gapEnd == gapStart) { return@run }
            val matcher = RegexPattern.smallStringsPattern(prog.memory)
            val gapBytes = ByteArray(gapEnd.subtract(gapStart).toInt())
            prog.memory.getBytes(gapStart, gapBytes)
            if (!matcher.test(MemoryMatch(gapStart, gapBytes, matcher.toMatcher(prog)))) { return@run }

            // Find small strings and add them
            var ptr = gapStart
            var strStart: Address? = null
            while (ptr < gapEnd) {
                if (prog.memory.getByte(ptr) != 0.toByte() && strStart == null) {
                    strStart = ptr
                } else if (prog.memory.getByte(ptr) == 0.toByte() && strStart != null) {
                    val strLength = ptr.subtract(strStart)
                    try {
                        prog.listing.createData(strStart, dt, strLength.toInt())
                        logger.debug("Created small string at 0x${strStart.offset.toString(16)}: " +
                            MemoryUtil.readProgramBytesToUTF8String(prog.memory, strStart, strLength.toInt())
                        )
                        totalCount++
                    } catch (_: CodeUnitInsertionException) {}  // ignore conflict definitions
                    strStart = null
                }
                ptr = ptr.add(1)
            }
        }}
    }

    companion object {
        // only detect string gaps that is smaller than this value
        const val FILL_GAP_MAX_SIZE = 0x100

        fun defaultSearcher(program: Program): MutableList<RegexSearcher> {
            return mutableListOf(AsciiSequenceSearcher(program), RegexSearcher(program, UNIX_COLOR_ASCII_REGEX))
        }
    }
}
